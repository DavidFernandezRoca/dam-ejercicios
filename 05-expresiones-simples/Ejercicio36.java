// 36. Comprobar si edad está comprendida entre 18 y 65 años, ambos incluidos.

public class Ejercicio36{
    public static void main(String args[]){
        int edad = 1;
        if (edad >= 18 && edad <= 65){
            System.out.println("Tu edad es valida");
        }
        else{
            System.out.println("Tu edad no es valida");
        }
    }
}
