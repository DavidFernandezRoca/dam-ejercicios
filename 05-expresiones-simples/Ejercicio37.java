// 37. Comprobar si numero está fuera del intervalo comprendido entre 10 y 20.

public class Ejercicio37{
    public static void main(String args[]){
        int numero = 1;
        if (numero > 20 || numero < 10){
            System.out.println("Tu numero esta fuera del intervalo");
        }
        else{
            System.out.println("Tu numero esta dentro del intervalo");
        }
    }
}
